import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
import {normalizeGames} from '../game-data.js';
import {writeSeo} from './seo.mjs';
export async function prepare(){
  const raw=JSON.parse(await readFile('games.json','utf8'));
  const catalog=normalizeGames(raw);
  const files=['seed-ids.js','core.js','icons.js','game-data.js','app.js'];
  const pieces=[];
  for(const file of files){
    let source=await readFile(file,'utf8');
    source=source.replace(/^import\s[^;]+;\s*$/gm,'').replace(/^export\s+(?=(?:async\s+)?(?:const|let|function|class)\b)/gm,'');
    if(/^\s*(?:import|export)\s/m.test(source))throw Error(`Unsupported module statement in ${file}`);
    pieces.push(`// Source: ${file}\n${source.trim()}\n`);
  }
  const snapshot=JSON.stringify(raw).replaceAll('<','\\u003c');
  const output=`// Generated by node scripts/prepare.mjs. Edit the source files and games.json.\n(()=>{\n'use strict';\nconst LOCAL_GAMES=${snapshot};\n${pieces.join('\n')}\n})();\n`;
  await writeFile('site.js',output);
  await writeSeo(raw);
  return {games:catalog.games.length,bytes:Buffer.byteLength(output)};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const result=await prepare();
  console.log(`Prepared file-compatible site.js with ${result.games} games (${result.bytes} bytes).`);
}
